import {basename} from 'node:path';
import {stringify} from 'yaml';
import {
  type ContractReferenceResolver,
  resolveContractReferences,
  resolveManifestValue,
} from './contract-references.js';
import type {
  ContractRead,
  ContractScalar,
  ContractShape,
  SandboxManifest,
} from './contract-schema.js';
import type {ContractFiles, LoadedContractCase} from './contracts.js';

export interface GeneratedFile {
  /** The file name inside `.shipfox-staging/workflows/`. */
  name: string;
  content: string;
}

export const CONTRACTS_WORKFLOW_NAME = 'contracts.yaml';
export const GENERATED_WORKFLOWS_DIRECTORY = '.shipfox-staging/workflows';

/**
 * Tools whose catalog `outputSchema` is closed, as `<provider>.<tool>`. The runtime already checks
 * their result against it, and the compiler rejects access to a field the schema doesn't name,
 * so a case checks their values and nothing else.
 */
export const VALUES_ONLY_TOOLS: ReadonlySet<string> = new Set();

const HEADER = [
  '# Generated by @shipfox/e2e-eval-workflows from e2e/suites/eval/workflows/cases/contracts.',
  '# Do not edit. Run `mise exec -- pnpm --filter @shipfox/e2e-eval-workflows contracts:generate`.',
  '',
].join('\n');

const JOB_KEY_PATTERN = /^[a-z][a-z0-9_]*$/u;
const FIELD_PATTERN = /^[A-Za-z_][A-Za-z0-9_]*$/u;
const FIXTURES_JOB = 'fixtures';

type Segment = {field: string} | {index: number};

interface WorkflowStep {
  key: string;
  tool: string;
  connection: string;
  with?: unknown;
  outputs?: Record<string, string>;
  gate?: {success: string};
}

function providerWorkflowName(provider: string): string {
  return `contracts-${provider}.yaml`;
}

function render(document: unknown): string {
  // A long gate stays on one line, so a change shows as one changed line.
  return `${HEADER}${stringify(document, {lineWidth: 0})}`;
}

/**
 * Compiles the real-mode contract workflows: one file per provider with a real case, and the
 * `contracts.yaml` that starts them. Files come back in name order. Nothing is written when no
 * case runs against the real provider.
 */
export function generateContractFiles(files: ContractFiles): GeneratedFile[] {
  const providers = [
    ...new Set(
      files.cases
        .filter(({definition}) => definition.modes.includes('real'))
        .map(({definition}) => definition.provider),
    ),
  ].sort();
  if (providers.length === 0) return [];

  const generated = providers.map((provider) => ({
    name: providerWorkflowName(provider),
    content: render(
      providerWorkflow({
        provider,
        manifest: files.manifest,
        cases: files.cases.filter(
          ({definition}) => definition.provider === provider && definition.modes.includes('real'),
        ),
      }),
    ),
  }));
  generated.push({
    name: CONTRACTS_WORKFLOW_NAME,
    content: render(startWorkflow(providers)),
  });
  return generated.sort((a, b) => a.name.localeCompare(b.name));
}

function startWorkflow(providers: string[]) {
  return {
    name: 'Contracts',
    runner: 'shipfox',
    triggers: {
      nightly: {source: 'cron', config: {schedule: '0 3 * * *', timezone: 'UTC'}},
      manual: {source: 'manual'},
    },
    jobs: {
      start: {
        checkout: false,
        steps: providers.map((provider) => ({
          key: provider,
          tool: 'start_workflow_run',
          connection: 'shipfox',
          with: {workflow: `${GENERATED_WORKFLOWS_DIRECTORY}/${providerWorkflowName(provider)}`},
        })),
      },
    },
  };
}

function providerWorkflow({
  provider,
  manifest,
  cases,
}: {
  provider: string;
  manifest: SandboxManifest;
  cases: LoadedContractCase[];
}) {
  const sandbox = manifest[provider];
  if (sandbox === undefined) throw new Error(`provider "${provider}" is not in sandbox.yaml`);

  const jobs: Record<string, unknown> = {};
  const fixtureSteps = Object.entries(sandbox.fixtures).flatMap(([name, fixture]) =>
    fixture.read === undefined
      ? []
      : [
          compileStep({
            key: name,
            read: fixture.read,
            provider,
            connection: sandbox.connection,
            manifest,
            origin: `${provider}.fixtures.${name}`,
          }),
        ],
  );
  if (fixtureSteps.length > 0) jobs[FIXTURES_JOB] = {checkout: false, steps: fixtureSteps};

  for (const loaded of [...cases].sort((a, b) => a.id.localeCompare(b.id))) {
    const jobKey = caseJobKey(loaded);
    if (jobs[jobKey] !== undefined) {
      throw new Error(`${loaded.id}: the job key "${jobKey}" is used by another case or reserved`);
    }
    jobs[jobKey] = caseJob({
      jobKey,
      loaded,
      connection: sandbox.connection,
      manifest,
    });
  }

  return {
    name: `Contracts ${provider}`,
    runner: 'shipfox',
    triggers: {manual: {source: 'manual'}},
    jobs,
  };
}

function caseJobKey({id}: LoadedContractCase): string {
  const key = basename(id).replaceAll('-', '_');
  if (!JOB_KEY_PATTERN.test(key)) {
    throw new Error(`${id}: the file name must make a job key of lowercase letters, digits, and _`);
  }
  return key;
}

function caseJob({
  jobKey,
  loaded,
  connection,
  manifest,
}: {
  jobKey: string;
  loaded: LoadedContractCase;
  connection: string;
  manifest: SandboxManifest;
}) {
  const {definition} = loaded;
  if (definition.kind !== 'read') {
    throw new Error(`${loaded.id}: cases of kind \`${definition.kind}\` are not generated yet`);
  }
  const keys = new Set<string>();
  const steps = definition.steps.map((step, index) => {
    if (step.effect !== undefined) {
      throw new Error(`${loaded.id}: a step \`effect\` is not generated yet`);
    }
    const key = step.key ?? (definition.steps.length === 1 ? jobKey : `${jobKey}_${index + 1}`);
    if (keys.has(key)) throw new Error(`${loaded.id}: the step key "${key}" is used twice`);
    keys.add(key);
    return compileStep({
      key,
      read: step,
      provider: definition.provider,
      connection,
      manifest,
      origin: `${loaded.id} steps.${index}`,
    });
  });
  return {checkout: false, steps};
}

/** The tool call of a step, and the checks of its result as output mappings and a gate. */
function compileStep({
  key,
  read,
  provider,
  connection,
  manifest,
  origin,
}: {
  key: string;
  read: ContractRead;
  provider: string;
  connection: string;
  manifest: SandboxManifest;
  origin: string;
}): WorkflowStep {
  const resolver = generationResolver({manifest, origin});
  const resolvedWith = resolveContractReferences(read.with, resolver) as Record<string, unknown>;
  const expect = resolveContractReferences(read.expect, resolver) as ContractRead['expect'];
  if (expect.includes !== undefined) {
    throw new Error(`${origin}: \`expect.includes\` is not generated yet`);
  }

  const outputs: Record<string, string> = {};
  const checks: string[] = [];
  const addCheck = ({name, mapping, check}: {name: string; mapping: string; check: string}) => {
    if (outputs[name] !== undefined) throw new Error(`${origin}: two checks are named "${name}"`);
    outputs[name] = `\${{ ${mapping} }}`;
    checks.push(check);
  };

  if (expect.shape !== undefined && !VALUES_ONLY_TOOLS.has(`${provider}.${read.tool}`)) {
    for (const leaf of shapeLeaves({shape: expect.shape, origin})) {
      const name = `shape_${segmentName(leaf.segments)}`;
      addCheck({
        name,
        mapping: presence({
          segments: leaf.segments,
          check: (accessor) => typeCheck({accessor, type: leaf.type}),
        }),
        check: `step.outputs.${name}`,
      });
    }
  }
  for (const [path, value] of Object.entries(expect.values ?? {})) {
    const segments = parsePath({path, origin});
    const name = `value_${segmentName(segments)}`;
    addCheck({
      name,
      mapping: `${presence({segments})} ? ${accessorOf(segments)} : ""`,
      check: valueCheck({accessor: `step.outputs.${name}`, value}),
    });
  }

  const tool = read.method === undefined ? read.tool : `${read.tool}.${read.method}`;
  return {
    key,
    tool,
    connection,
    ...(Object.keys(resolvedWith).length === 0 ? {} : {with: resolvedWith}),
    ...(checks.length === 0
      ? {}
      : // The gate decides the step's result even when the call failed, so it has to see the status.
        {outputs, gate: {success: ['step.status == "succeeded"', ...checks].join(' && ')}}),
  };
}

function generationResolver({
  manifest,
  origin,
}: {
  manifest: SandboxManifest;
  origin: string;
}): ContractReferenceResolver {
  const unsupported = (token: string) => () => {
    throw new Error(`${origin}: ${token} is not generated yet`);
  };
  return {
    fixture: (reference) => {
      const value = resolveManifestValue({manifest, reference});
      if (value === undefined)
        throw new Error(`${origin}: a fixture reference is not in the manifest`);
      return value;
    },
    target: unsupported('$target'),
    steps: unsupported('$steps'),
    marker: unsupported('$marker'),
  };
}

interface ShapeLeaf {
  segments: Segment[];
  type: 'string' | 'number' | 'boolean' | 'list' | 'object';
}

/** Flattens a shape to the typed leaves it names. `[{...}]` reads the first item of a list. */
function shapeLeaves({
  shape,
  origin,
  prefix = [],
}: {
  shape: ContractShape;
  origin: string;
  prefix?: Segment[];
}): ShapeLeaf[] {
  if (typeof shape === 'string') return [{segments: prefix, type: shape}];
  if (Array.isArray(shape)) {
    return shapeLeaves({shape: shape[0], origin, prefix: [...prefix, {index: 0}]});
  }
  return Object.entries(shape).flatMap(([field, child]) => {
    if (!FIELD_PATTERN.test(field)) {
      throw new Error(`${origin}: the shape field "${field}" must be letters, digits, and _`);
    }
    return shapeLeaves({shape: child, origin, prefix: [...prefix, {field}]});
  });
}

function parsePath({path, origin}: {path: string; origin: string}): Segment[] {
  return [...path.matchAll(/([A-Za-z_][A-Za-z0-9_]*)|\[(\d+)\]/gu)].map(([, field, index]) => {
    if (field !== undefined) return {field};
    if (index !== undefined) return {index: Number(index)};
    throw new Error(`${origin}: "${path}" is not a path`);
  });
}

function segmentName(segments: Segment[]): string {
  return segments.map((segment) => ('field' in segment ? segment.field : segment.index)).join('_');
}

function accessorOf(segments: Segment[], root = 'result'): string {
  return segments.reduce(
    (accessor, segment) =>
      'field' in segment ? `${accessor}.${segment.field}` : `${accessor}[${segment.index}]`,
    root,
  );
}

/**
 * A CEL condition that is true when every step of the path exists. `has()` can't take an index, so
 * past a list item the rest of the path reads a scoped copy of that item.
 */
function presence({
  segments,
  check,
  root = 'result',
  scope = 0,
}: {
  segments: Segment[];
  check?: ((accessor: string) => string) | undefined;
  root?: string;
  scope?: number;
}): string {
  const guards: string[] = [];
  let accessor = root;
  for (const [position, segment] of segments.entries()) {
    if ('field' in segment) {
      accessor = `${accessor}.${segment.field}`;
      guards.push(`has(${accessor})`);
      continue;
    }
    const item = `i${scope}`;
    guards.push(`type(${accessor}) == list`, `size(${accessor}) > ${segment.index}`);
    const inner = presence({
      segments: segments.slice(position + 1),
      check,
      root: item,
      scope: scope + 1,
    });
    if (inner !== '') guards.push(`[${accessor}[${segment.index}]].all(${item}, ${inner})`);
    return guards.join(' && ');
  }
  if (check !== undefined) guards.push(check(accessor));
  return guards.join(' && ');
}

function typeCheck({accessor, type}: {accessor: string; type: ShapeLeaf['type']}): string {
  switch (type) {
    case 'string':
      return `type(${accessor}) == string`;
    case 'number':
      // A JSON number is an int or a double depending on how it was read.
      return `(type(${accessor}) == int || type(${accessor}) == double)`;
    case 'boolean':
      return `type(${accessor}) == bool`;
    case 'list':
      return `type(${accessor}) == list`;
    case 'object':
      return `type(${accessor}) == map`;
  }
}

/** A comparison that never errors on a result of another type: it is false instead. */
function valueCheck({accessor, value}: {accessor: string; value: ContractScalar}): string {
  if (typeof value === 'string') {
    return `type(${accessor}) == string && ${accessor} == ${JSON.stringify(value)}`;
  }
  if (typeof value === 'boolean') return `type(${accessor}) == bool && ${accessor} == ${value}`;
  return `${typeCheck({accessor, type: 'number'})} && ${accessor} == ${value}`;
}
