import {basename} from 'node:path';
import {stringify} from 'yaml';
import {
  type ContractReferenceResolver,
  resolveContractReferences,
  resolveManifestValue,
} from './contract-references.js';
import type {
  ContractRead,
  ContractScalar,
  ContractShape,
  SandboxManifest,
} from './contract-schema.js';
import type {ContractFiles, LoadedContractCase} from './contracts.js';

export interface GeneratedFile {
  /** The file name inside `.shipfox-staging/workflows/`. */
  name: string;
  content: string;
}

export const CONTRACTS_WORKFLOW_NAME = 'contracts.yaml';
export const GENERATED_WORKFLOWS_DIRECTORY = '.shipfox-staging/workflows';

/**
 * Tools whose catalog `outputSchema` is closed, as `<provider>.<tool>`. The runtime already checks
 * their result against it, and the compiler rejects access to a field the schema doesn't name,
 * so a case checks their values and nothing else.
 */
export const VALUES_ONLY_TOOLS: ReadonlySet<string> = new Set();

const HEADER = [
  '# Generated by @shipfox/e2e-eval-workflows from e2e/suites/eval/workflows/cases/contracts.',
  '# Do not edit. Run `mise exec -- pnpm --filter @shipfox/e2e-eval-workflows contracts:generate`.',
  '',
].join('\n');

const JOB_KEY_PATTERN = /^[a-z][a-z0-9_]*$/u;
const FIELD_PATTERN = /^[A-Za-z_][A-Za-z0-9_]*$/u;
const FIXTURES_JOB = 'fixtures';
// The variable of an `exists()` over a list, so it can't clash with the `i<n>` of `presence()`.
const ITEM = 'item';

type Segment = {field: string} | {index: number};

interface WorkflowStep {
  key: string;
  tool: string;
  connection: string;
  with?: unknown;
  outputs?: Record<string, string>;
  gate?: {success: string};
}

/** A CEL expression in a workflow field. */
function interpolation(source: string): string {
  return `\${{ ${source} }}`;
}

function providerWorkflowName(provider: string): string {
  return `contracts-${provider}.yaml`;
}

function render(document: unknown): string {
  // A long gate stays on one line, so a change shows as one changed line. YAML 1.1 quoting keeps a
  // string such as `2026-09-01` from reading back as a date, which the server's parser does.
  return `${HEADER}${stringify(document, {lineWidth: 0, version: '1.1'})}`;
}

export type ContractGenerationMode = 'real' | 'fake';

/**
 * Compiles the contract workflows of one mode: one file per provider with a case in that mode, and
 * for `real` the `contracts.yaml` that starts them. Files come back in name order. Nothing comes
 * back when no case runs in the mode.
 *
 * Only `real` files have a `fixtures` job. It tells a broken sandbox from a broken tool, and the
 * fake is seeded from the same fixtures, so the cases show both.
 */
export function generateContractFiles(
  files: ContractFiles,
  {mode = 'real'}: {mode?: ContractGenerationMode} = {},
): GeneratedFile[] {
  const inMode = files.cases.filter(({definition}) => definition.modes.includes(mode));
  const providers = [...new Set(inMode.map(({definition}) => definition.provider))].sort();
  if (providers.length === 0) return [];

  const generated = providers.map((provider) => ({
    name: providerWorkflowName(provider),
    content: render(
      providerWorkflow({
        provider,
        mode,
        manifest: files.manifest,
        cases: inMode.filter(({definition}) => definition.provider === provider),
      }),
    ),
  }));
  if (mode === 'real') {
    generated.push({
      name: CONTRACTS_WORKFLOW_NAME,
      content: render(startWorkflow(providers)),
    });
  }
  return generated.sort((a, b) => a.name.localeCompare(b.name));
}

function startWorkflow(providers: string[]) {
  return {
    name: 'Contracts',
    runner: 'shipfox',
    triggers: {
      nightly: {source: 'cron', config: {schedule: '0 3 * * *', timezone: 'UTC'}},
      manual: {source: 'manual'},
    },
    jobs: {
      start: {
        checkout: false,
        steps: providers.map((provider) => ({
          key: provider,
          tool: 'start_workflow_run',
          connection: 'shipfox',
          with: {workflow: `${GENERATED_WORKFLOWS_DIRECTORY}/${providerWorkflowName(provider)}`},
        })),
      },
    },
  };
}

function providerWorkflow({
  provider,
  mode,
  manifest,
  cases,
}: {
  provider: string;
  mode: ContractGenerationMode;
  manifest: SandboxManifest;
  cases: LoadedContractCase[];
}) {
  const sandbox = manifest[provider];
  if (sandbox === undefined) throw new Error(`provider "${provider}" is not in sandbox.yaml`);

  const jobs: Record<string, unknown> = {};
  const fixtureSteps = Object.entries(sandbox.fixtures).flatMap(([name, fixture]) =>
    fixture.read === undefined || mode === 'fake'
      ? []
      : [
          compileStep({
            key: name,
            read: fixture.read,
            provider,
            connection: sandbox.connection,
            manifest,
            origin: `${provider}.fixtures.${name}`,
          }),
        ],
  );
  if (fixtureSteps.length > 0) jobs[FIXTURES_JOB] = {checkout: false, steps: fixtureSteps};

  const addJob = ({key, job, origin}: {key: string; job: unknown; origin: string}) => {
    if (jobs[key] !== undefined) {
      throw new Error(`${origin}: the job key "${key}" is used by another case or reserved`);
    }
    jobs[key] = job;
  };

  for (const loaded of [...cases].sort((a, b) => a.id.localeCompare(b.id))) {
    const key = caseJobKey(loaded);
    addJob({
      key,
      origin: loaded.id,
      job: caseJob({jobKey: key, loaded, connection: sandbox.connection, manifest}),
    });
  }

  return {
    name: `Contracts ${provider}`,
    runner: 'shipfox',
    triggers: {manual: {source: 'manual'}},
    jobs,
  };
}

export function caseJobKey({id}: LoadedContractCase): string {
  const key = basename(id).replaceAll('-', '_');
  if (!JOB_KEY_PATTERN.test(key)) {
    throw new Error(`${id}: the file name must make a job key of lowercase letters, digits, and _`);
  }
  return key;
}

function caseJob({
  jobKey,
  loaded,
  connection,
  manifest,
}: {
  jobKey: string;
  loaded: LoadedContractCase;
  connection: string;
  manifest: SandboxManifest;
}) {
  const {definition} = loaded;
  const keys = definition.steps.map(
    (step, index) =>
      step.key ?? (definition.steps.length === 1 ? jobKey : `${jobKey}_${index + 1}`),
  );
  const references: StepReferences = {keys: new Set(keys), requests: new Map()};
  const steps: WorkflowStep[] = [];
  for (const [index, step] of definition.steps.entries()) {
    const key = keys[index] as string;
    const origin = `${loaded.id} steps.${index}`;
    if (steps.some((compiled) => compiled.key === key)) {
      throw new Error(`${loaded.id}: the step key "${key}" is used twice`);
    }
    steps.push(
      compileStep({
        key,
        read: step,
        provider: definition.provider,
        connection,
        manifest,
        origin,
        allowTargets: definition.kind === 'error',
        references,
      }),
    );
    if (step.effect === undefined) continue;
    if (definition.kind !== 'round-trip') {
      throw new Error(`${origin}: a step \`effect\` is only for cases of kind \`round-trip\``);
    }
    // The effect is its own step right after the write, so a failed write fails before its read.
    const effectKey = `${key}_effect`;
    if (keys.includes(effectKey)) {
      throw new Error(`${origin}: the effect key "${effectKey}" is used by another step`);
    }
    steps.push(
      compileStep({
        key: effectKey,
        read: step.effect,
        provider: definition.provider,
        connection,
        manifest,
        origin: `${origin} effect`,
        references,
      }),
    );
  }
  return {checkout: false, steps: withReferencedOutputs({steps, references, origin: loaded.id})};
}

/** The `$steps` references of a case, by the key of the step they read and the output they name. */
interface StepReferences {
  keys: ReadonlySet<string>;
  requests: Map<string, Map<string, Segment[]>>;
}

/** Gives each step the outputs that later steps read through `$steps`. */
function withReferencedOutputs({
  steps,
  references,
  origin,
}: {
  steps: WorkflowStep[];
  references: StepReferences;
  origin: string;
}): WorkflowStep[] {
  return steps.map((step) => {
    const requested = references.requests.get(step.key);
    if (requested === undefined) return step;
    const outputs = {...step.outputs};
    for (const [name, segments] of requested) {
      if (outputs[name] !== undefined)
        throw new Error(`${origin}: two outputs are named "${name}"`);
      outputs[name] = interpolation(`${presence({segments})} ? ${accessorOf(segments)} : ""`);
    }
    return {...step, outputs};
  });
}

/** The tool call of a step, and the checks of its result as output mappings and a gate. */
function compileStep({
  key,
  read,
  provider,
  connection,
  manifest,
  origin,
  allowTargets = false,
  references,
}: {
  key: string;
  read: ContractRead & {expect: {error?: string | undefined}};
  provider: string;
  connection: string;
  manifest: SandboxManifest;
  origin: string;
  allowTargets?: boolean;
  references?: StepReferences;
}): WorkflowStep {
  // `$steps` and `$marker` go in `with`. A gate reads the step's own result and nothing else, so
  // it can't compare that result to another step's output or to the run id.
  const resolvedWith = resolveContractReferences(
    read.with,
    generationResolver({manifest, origin, allowTargets, references}),
  ) as Record<string, unknown>;
  const expect = resolveContractReferences(
    read.expect,
    generationResolver({manifest, origin, allowTargets}),
  ) as ContractRead['expect'] & {
    error?: string | undefined;
  };
  const tool = read.method === undefined ? read.tool : `${read.tool}.${read.method}`;
  const call = {
    key,
    tool,
    connection,
    ...(Object.keys(resolvedWith).length === 0 ? {} : {with: resolvedWith}),
  };
  if (expect.error !== undefined) {
    // The failure is the contract: a call that succeeds fails the step, so a target that stops
    // failing fails its case.
    return {
      ...call,
      gate: {
        success: `step.status == "failed" && step.error.code == ${JSON.stringify(expect.error)}`,
      },
    };
  }

  const outputs: Record<string, string> = {};
  const checks: string[] = [];
  const addCheck = ({name, mapping, check}: {name: string; mapping: string; check: string}) => {
    if (outputs[name] !== undefined) throw new Error(`${origin}: two checks are named "${name}"`);
    outputs[name] = interpolation(mapping);
    checks.push(check);
  };

  if (expect.shape !== undefined && !VALUES_ONLY_TOOLS.has(`${provider}.${read.tool}`)) {
    for (const leaf of shapeLeaves({shape: expect.shape, origin})) {
      const name = `shape_${segmentName(leaf.segments)}`;
      addCheck({
        name,
        mapping: presence({
          segments: leaf.segments,
          check: (accessor) => typeCheck({accessor, type: leaf.type}),
        }),
        check: `step.outputs.${name}`,
      });
    }
  }
  for (const [path, value] of Object.entries(expect.values ?? {})) {
    const segments = parsePath({path, origin});
    const name = `value_${segmentName(segments)}`;
    addCheck({
      name,
      mapping: stringValueMapping({segments, value}),
      check: valueCheck({accessor: `step.outputs.${name}`, value}),
    });
  }

  for (const [path, item] of Object.entries(expect.includes ?? {})) {
    const segments = parsePath({path, origin});
    const name = `includes_${segmentName(segments)}`;
    // An index in the list's path opens a scope per index, so the item's own scopes start after.
    const scope = segments.filter((segment) => 'index' in segment).length;
    const conditions = Object.entries(item).map(([field, value]) =>
      presence({
        segments: parsePath({path: field, origin}),
        root: ITEM,
        scope,
        check: (accessor) => valueCheck({accessor, value}),
      }),
    );
    addCheck({
      name,
      mapping: presence({
        segments,
        check: (accessor) =>
          `type(${accessor}) == type([]) && ${accessor}.exists(${ITEM}, ${conditions.join(' && ')})`,
      }),
      check: `step.outputs.${name}`,
    });
  }

  for (const check of patternChecks({expect, origin})) addCheck(check);

  return {
    ...call,
    ...(checks.length === 0
      ? {}
      : // The gate decides the step's result even when the call failed, so it has to see the status.
        {outputs, gate: {success: ['step.status == "succeeded"', ...checks].join(' && ')}}),
  };
}

/** The regular-expression checks: `matches` on a text value at a path, and `text` on the result. */
function patternChecks({
  expect,
  origin,
}: {
  expect: ContractRead['expect'];
  origin: string;
}): {name: string; mapping: string; check: string}[] {
  const checks = Object.entries(expect.matches ?? {}).map(([path, pattern]) => {
    const segments = parsePath({path, origin});
    const name = `matches_${segmentName(segments)}`;
    const mapping = presence({
      segments,
      check: (accessor) =>
        `type(${accessor}) == type("") && ${accessor}.matches(${JSON.stringify(pattern)})`,
    });
    return {name, mapping, check: `step.outputs.${name}`};
  });
  const text = (expect.text ?? []).map((pattern, index) => ({
    name: `text_${index}`,
    mapping: `type(result) == type("") && result.matches(${JSON.stringify(pattern)})`,
    check: `step.outputs.text_${index}`,
  }));
  return [...checks, ...text];
}

function generationResolver({
  manifest,
  origin,
  allowTargets,
  references,
}: {
  manifest: SandboxManifest;
  origin: string;
  allowTargets: boolean;
  references?: StepReferences | undefined;
}): ContractReferenceResolver {
  const withOnly = (token: string) => () => {
    throw new Error(`${origin}: ${token} is only for the \`with\` of a step in a case`);
  };
  return {
    fixture: (reference) => {
      const value = resolveManifestValue({manifest, reference});
      if (value === undefined)
        throw new Error(`${origin}: a fixture reference is not in the manifest`);
      return value;
    },
    // Targets are for error cases. Fixture reads and other cases never see one.
    target: (reference) => {
      if (!allowTargets) throw new Error(`${origin}: $target is only for cases of kind \`error\``);
      const value = resolveManifestValue({manifest, reference});
      if (value === undefined)
        throw new Error(`${origin}: a target reference is not in the manifest`);
      return value;
    },
    steps:
      references === undefined
        ? withOnly('$steps')
        : ({key, path}) => {
            if (!references.keys.has(key)) {
              throw new Error(`${origin}: $steps.${key} names a step key the case doesn't have`);
            }
            const segments = parsePath({path, origin});
            const name = `ref_${segmentName(segments)}`;
            const requested = references.requests.get(key) ?? new Map<string, Segment[]>();
            requested.set(name, segments);
            references.requests.set(key, requested);
            return interpolation(`steps.${key}.outputs.${name}`);
          },
    // The run id makes every written object traceable to its run.
    marker:
      references === undefined ? withOnly('$marker') : () => `contract-${interpolation('run.id')}`,
    // A Unix timestamp, for a tool that schedules something. It stays a number as a whole value.
    inOneHour:
      references === undefined
        ? withOnly('$in_one_hour')
        : () => interpolation('int(run.created_at) + 3600'),
  };
}

interface ShapeLeaf {
  segments: Segment[];
  type: 'string' | 'number' | 'boolean' | 'list' | 'object';
}

/** Flattens a shape to the typed leaves it names. `[{...}]` reads the first item of a list. */
function shapeLeaves({
  shape,
  origin,
  prefix = [],
}: {
  shape: ContractShape;
  origin: string;
  prefix?: Segment[];
}): ShapeLeaf[] {
  if (typeof shape === 'string') return [{segments: prefix, type: shape}];
  if (Array.isArray(shape)) {
    return shapeLeaves({shape: shape[0], origin, prefix: [...prefix, {index: 0}]});
  }
  return Object.entries(shape).flatMap(([field, child]) => {
    if (!FIELD_PATTERN.test(field)) {
      throw new Error(`${origin}: the shape field "${field}" must be letters, digits, and _`);
    }
    return shapeLeaves({shape: child, origin, prefix: [...prefix, {field}]});
  });
}

function parsePath({path, origin}: {path: string; origin: string}): Segment[] {
  return [...path.matchAll(/([A-Za-z_][A-Za-z0-9_]*)|\[(\d+)\]/gu)].map(([, field, index]) => {
    if (field !== undefined) return {field};
    if (index !== undefined) return {index: Number(index)};
    throw new Error(`${origin}: "${path}" is not a path`);
  });
}

function segmentName(segments: Segment[]): string {
  return segments.map((segment) => ('field' in segment ? segment.field : segment.index)).join('_');
}

function accessorOf(segments: Segment[], root = 'result'): string {
  return segments.reduce(
    (accessor, segment) =>
      'field' in segment ? `${accessor}.${segment.field}` : `${accessor}[${segment.index}]`,
    root,
  );
}

/**
 * A CEL condition that is true when every step of the path exists. `has()` can't take an index, so
 * past a list item the rest of the path reads a scoped copy of that item.
 */
function presence({
  segments,
  check,
  root = 'result',
  scope = 0,
}: {
  segments: Segment[];
  check?: ((accessor: string) => string) | undefined;
  root?: string;
  scope?: number;
}): string {
  const guards: string[] = [];
  let accessor = root;
  for (const [position, segment] of segments.entries()) {
    if ('field' in segment) {
      accessor = `${accessor}.${segment.field}`;
      guards.push(`has(${accessor})`);
      continue;
    }
    const item = `i${scope}`;
    guards.push(`type(${accessor}) == type([])`, `size(${accessor}) > ${segment.index}`);
    const inner = presence({
      segments: segments.slice(position + 1),
      check,
      root: item,
      scope: scope + 1,
    });
    if (inner !== '') guards.push(`[${accessor}[${segment.index}]].all(${item}, ${inner})`);
    return guards.join(' && ');
  }
  if (check !== undefined) guards.push(check(accessor));
  return guards.join(' && ');
}

function typeCheck({accessor, type}: {accessor: string; type: ShapeLeaf['type']}): string {
  switch (type) {
    case 'string':
      return `type(${accessor}) == type("")`;
    case 'number':
      // A JSON number is an int or a double depending on how it was read.
      return `(type(${accessor}) == type(1) || type(${accessor}) == type(1.0))`;
    case 'boolean':
      return `type(${accessor}) == type(true)`;
    case 'list':
      return `type(${accessor}) == type([])`;
    case 'object':
      return `type(${accessor}) == type({})`;
  }
}

// A dyn mapping is declared as a json output, and the declaration parses string values, so an id
// like "901222980414" would come back as a number. A string-typed mapping skips the parse. A
// result of another type maps to "" and fails the check.
function stringValueMapping({
  segments,
  value,
}: {
  segments: Segment[];
  value: ContractScalar;
}): string {
  if (!changedByJsonParse(value)) return `${presence({segments})} ? ${accessorOf(segments)} : ""`;
  const check = (accessor: string) => typeCheck({accessor, type: 'string'});
  return `${presence({segments, check})} ? string(${accessorOf(segments)}) : ""`;
}

function changedByJsonParse(value: ContractScalar): boolean {
  if (typeof value !== 'string') return false;
  try {
    return JSON.parse(value) !== value;
  } catch {
    return false;
  }
}

/** A comparison that never errors on a result of another type: it is false instead. */
function valueCheck({accessor, value}: {accessor: string; value: ContractScalar}): string {
  if (typeof value === 'string') {
    return `type(${accessor}) == type("") && ${accessor} == ${JSON.stringify(value)}`;
  }
  if (typeof value === 'boolean')
    return `type(${accessor}) == type(true) && ${accessor} == ${value}`;
  return `${typeCheck({accessor, type: 'number'})} && ${accessor} == ${value}`;
}
